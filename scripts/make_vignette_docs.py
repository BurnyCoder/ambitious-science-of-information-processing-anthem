"""Write docs/vignettes.md: the figure-card catalog with times, trigger words, badges and sources.

Local: reads the placed cards from video/public/timeline.json (so times and FIG numbers match the video) and
the trigger words from content/vignettes.toml, and renders one Markdown table per song section.
Global context: the catalog is generated, never hand-edited, so the docs cannot drift from the card data.
Usage: uv run python -I scripts/make_vignette_docs.py   (after `uv run anthem --stage timeline`)
"""

import json  # timeline
import sys  # import path
import tomllib  # catalog
from pathlib import Path  # paths

ROOT = Path(__file__).resolve().parents[1]  # repo root
sys.path.insert(0, str(ROOT / "src"))  # the pipeline package
from anthem.lyrics import section_keys  # same section addressing as the placement code

HEADER = """# Figure cards (the illustration track)

Generated by `scripts/make_vignette_docs.py` from `video/public/timeline.json` and `content/vignettes.toml`. Do not edit by hand.

Every card appears 0.15 s before the sung word it illustrates and carries a provenance badge:

| Badge | Meaning |
|---|---|
| released data | numbers or figures read from files released by the authors or a well-known third party (provenance and sha256 in [`reports/data/exp07_sources.json`](../reports/data/exp07_sources.json)) |
| published numbers | values quoted from a paper's text or tables |
| live math | computed in the video from the formula (`video/src/lib/mathviz.ts`) |
| from the paper | a formula or claim stated in the cited paper |
| schematic | drawn by us to illustrate the cited idea; not data |

How cards are placed and drawn: [architecture](architecture.md). Checks of every on-screen number: [experiment 7](../reports/exp07_provenance.md).
"""


def main() -> None:
    tl = json.loads((ROOT / "video" / "public" / "timeline.json").read_text(encoding="utf-8"))
    spec = tomllib.loads((ROOT / "content" / "vignettes.toml").read_text(encoding="utf-8"))["vignette"]
    out = [HEADER]
    for sec in tl["sections"]:
        cards = [(i + 1, v) for i, v in enumerate(tl["vignettes"]) if v["sectionIndex"] == sec["index"]]
        if not cards:
            continue
        out.append(f"\n## {sec['label']} ({sec['scene']}, {sec['startS']:.1f}–{sec['endS']:.1f} s)\n")
        out.append("| FIG | Time (s) | Trigger | Card | Badge | Source |\n|---|---|---|---|---|---|")
        for fig, v in cards:
            entry = next(e for e in spec if e["title"] == v["title"] and e["section"] in section_keys(sec["kind"], sec["occurrence"]))
            src = f"[{v['cite']}]({v['url']})" if v["url"] else v["cite"]
            out.append(f"| {fig} | {v['startS']:.1f}–{v['endS']:.1f} | `{entry['trigger']}` | **{v['title']}** ({v['id']}) | {v['badge']} | {src} |")
    (ROOT / "docs" / "vignettes.md").write_text("\n".join(out) + "\n", encoding="utf-8")
    print(f"docs/vignettes.md: {len(tl['vignettes'])} cards")


if __name__ == "__main__":
    main()
